import json
import os
from pathlib import Path

import nd2
import numpy as np
import pandas as pd
from PIL import Image, ImageDraw

root = Path(
    os.environ.get(
        "LNP_RESULTS_DIR", str(Path.home() / "data" / "lnp-tracking-spotiflow")
    )
)
paths = {
    "Previous Picasso": root.parent
    / "lnp-tracking-picasso/LISCA_review_A549_exp_60x006/detections.csv",
    "Refined Picasso": root.parent
    / "lnp-tracking-picasso-refined/LISCA_review_A549_exp_60x006/detections.csv",
    "Spotiflow": root / "LISCA_review_A549_exp_60x006_pilot.csv",
}
with nd2.ND2File(root.parent / "LISCA review A549 exp 60x006.nd2") as f:
    im = f.read_frame(0)[0].copy()
assets = {}
for label, (x, y) in {
    "Faint puncta": (200, 400),
    "Close neighbors": (600, 100),
}.items():
    patch = im[y : y + 180, x : x + 180]
    lo, hi = np.percentile(patch, [1, 99.8])
    v = np.clip((patch.astype(float) - lo) / (hi - lo) * 255, 0, 255).astype("uint8")
    base = Image.fromarray(v).convert("RGB").resize((540, 540))
    entries = {}
    p = root / (label.replace(" ", "_") + "_raw.png")
    base.save(p)
    entries["Raw"] = str(p)
    for method, csv in paths.items():
        d = pd.read_csv(csv)
        if "frame" in d:
            d = d[d.frame == 0]
        xcol = "x_raw" if "x_raw" in d else "x"
        ycol = "y_raw" if "y_raw" in d else "y"
        canvas = base.copy()
        draw = ImageDraw.Draw(canvas)
        for _, a in d.iterrows():
            xx = (a[xcol] - x) * 3
            yy = (a[ycol] - y) * 3
            if 0 <= xx < 540 and 0 <= yy < 540:
                draw.ellipse(
                    (xx - 7, yy - 7, xx + 7, yy + 7), outline=(60, 255, 90), width=1
                )
        p = root / (label.replace(" ", "_") + "_" + method.replace(" ", "_") + ".png")
        canvas.save(p)
        entries[method] = str(p)
    assets[label] = entries
html = """<!doctype html><html><style>select,button{font:inherit;padding:6px;color:var(--foreground);background:var(--card);border:1px solid var(--border);border-radius:var(--radius)}.grid{display:grid;grid-template-columns:1fr 1fr;gap:12px;margin-top:12px}.grid img{width:100%;display:block}.label{font-size:13px;margin:5px 0}.note{font-size:13px;color:var(--muted-foreground)}@media(max-width:450px){.grid{gap:5px}}</style><label>006, frame 0 · crop <select id="crop"><option>Faint puncta</option><option>Close neighbors</option></select></label><button id="toggle" style="margin-left:8px">Hide circles</button><div class="grid" id="grid"></div><p class="note">Same raw pixels and contrast in every panel. Green circles show all detections, independent of track length. These are visual sensitivity examples, not comprehensive accuracy validation.</p><script>const assets=ASSETS;let visible=true;function render(){const a=assets[document.getElementById('crop').value];const raw=a.Raw;document.getElementById('grid').innerHTML=Object.entries(a).map(([k,v])=>`<div><div class="label">${k}</div><img alt="${k}" src="${visible?v:raw}"></div>`).join('')}document.getElementById('crop').onchange=render;document.getElementById('toggle').onclick=()=>{visible=!visible;document.getElementById('toggle').textContent=visible?'Hide circles':'Show circles';render()};render()</script></html>""".replace(
    "ASSETS", json.dumps(assets)
)
# Inline images in JS assets: local image paths generated by JS aren't automatically inlined by renderer.
import base64

for entries in assets.values():
    for p in entries.values():
        html = html.replace(
            p,
            "data:image/png;base64," + base64.b64encode(Path(p).read_bytes()).decode(),
        )
(root / "detection_review.html").write_text(html)
